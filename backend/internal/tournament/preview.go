package tournament

import (
	"fmt"
	"strconv"
)

// PreviewRequest is a draw somebody wants to see without owning a tournament.
//
// It is the whole input: a format, a field size, and the settings that change
// the shape of the result. There is no stage, no entry list and no account
// behind it, which is the point — a page that says "8 team double elimination
// bracket" has to be able to show one to a stranger.
type PreviewRequest struct {
	Format string `json:"format"`
	// How many take part. Ignored when Names is given.
	Teams int `json:"teams"`
	// Real names, when the caller has them. Otherwise the field is numbered.
	Names  []string    `json:"names"`
	Config StageConfig `json:"config"`
}

// PreviewLimit caps the field a stranger can ask to have drawn.
//
// This endpoint is unauthenticated and writes nothing, so the only thing worth
// protecting is the CPU: a round robin is quadratic in the field, and nothing
// stops somebody asking for ten thousand teams and 50 million fixtures. 128 is
// comfortably past the largest real tournament anybody has run through this
// and cheap enough that the request is not worth making twice.
const PreviewLimit = 128

// PreviewPlan draws a stage that does not exist.
//
// It runs the same generators as a real one — PlanStage is the version that
// knows how to read a stage record and an entry list, and this is the version
// that is handed those things directly. Both end in the same four functions,
// which is the property worth having: the bracket on a marketing page and the
// bracket in a hall come out of one implementation, so a page cannot promise a
// draw the product would not produce.
//
// Nothing here touches the database, so there is nothing to authorise.
func PreviewPlan(req PreviewRequest) (*StagePlan, error) {
	// A stage fed by an earlier stage reads that stage's finished tables, and
	// there is no earlier stage here. Groups-then-playoff previews as its two
	// halves rather than as one call.
	if req.Config.SeedFrom != nil {
		return nil, fmt.Errorf("seedFrom needs a real stage to read from")
	}

	names := req.Names
	if len(names) == 0 {
		if req.Teams < 2 {
			return nil, fmt.Errorf("a draw needs at least 2 teams, got %d", req.Teams)
		}
		if req.Teams > PreviewLimit {
			return nil, fmt.Errorf("at most %d teams, got %d", PreviewLimit, req.Teams)
		}
		names = numberedField(req.Teams)
	}
	if len(names) < 2 {
		return nil, fmt.Errorf("a draw needs at least 2 teams, got %d", len(names))
	}
	if len(names) > PreviewLimit {
		return nil, fmt.Errorf("at most %d teams, got %d", PreviewLimit, len(names))
	}

	// Entries do not exist, so the drafts carry positional ids. They are never
	// written and never resolved — what a preview renders is the label, which
	// for a direct slot is the name.
	ids := make([]string, len(names))
	for i := range names {
		ids[i] = "preview" + strconv.Itoa(i+1)
	}

	switch req.Format {
	case "round_robin":
		return PlanRoundRobin(ids, req.Config), nil
	case "swiss":
		return PlanSwiss(ids, req.Config), nil
	case "single_elim", "double_elim":
		seeds := make([]bracketSeed, len(ids))
		for i, id := range ids {
			seeds[i] = bracketSeed{
				Entry:      id,
				SourceType: "direct",
				Label:      directLabel(names[i]),
			}
		}
		if req.Format == "double_elim" {
			return PlanDoubleElimination(seeds, req.Config), nil
		}
		return PlanSingleElimination(seeds, req.Config), nil
	case "ladder":
		// Accepted by the schema and generated by nothing. Saying so is better
		// than an empty plan a caller would read as "no matches".
		return nil, fmt.Errorf("ladder is not generated yet")
	default:
		return nil, fmt.Errorf("unknown format %q", req.Format)
	}
}

// numberedField is "Team 1", "Team 2", … — English on purpose.
//
// A caller that wants the field in its own language sends the names; this is
// the fallback for a caller that has none, and the wording of a placeholder is
// not worth a locale negotiation on an endpoint with no session.
func numberedField(n int) []string {
	names := make([]string, n)
	for i := range names {
		names[i] = "Team " + strconv.Itoa(i+1)
	}
	return names
}
